  React.ElementRef<typeof SelectPrimitive.Label>,
  React.ComponentPropsWithoutRef<typeof SelectPrimitive.Label>
>(({ className, ...props }, ref) => (
  <SelectPrimitive.Label ref={ref} className={cn("py-spacing-2xs pl-spacing-xl pr-spacing-xs text-sm font-semibold", className)} {...props} />
));
